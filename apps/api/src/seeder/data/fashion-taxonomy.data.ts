const opt = (...values: string[]): SeedAttributeOption[] => values.map((value) => ({ value }));
const colorOpt = (pairs: ReadonlyArray<readonly [string, string]>): SeedAttributeOption[] =>
  pairs.map(([value, hexColor]) => ({ value, hexColor }));
const pt = (
  slug: string,
  attributes: string[],
  nameEn?: string,
  nameBn?: string,
): SeedProductType => ({ slug, attributes, nameEn, nameBn });

/** Colour + size variant (the common Fashion sellable combination). */
const cv = (
  color: string,
  size: string,
  sizeAttr: string,
  sku: string,
  price: number,
  stock: number,
): SeedVerticalVariant => ({
  nameEn: `${color} / ${size}`,
  nameBn: `${color} / ${size}`,
  sku,
  price,
  stock,
  attributes: { 'fashion-color': color, [sizeAttr]: size },
});

/** Colour-only variant (one-size accessories, saree, hijab, bags…). */
const cv1 = (color: string, sku: string, price: number, stock: number): SeedVerticalVariant => ({
  nameEn: color,
  nameBn: color,
  sku,
  price,
  stock,
  attributes: { 'fashion-color': color },
});

